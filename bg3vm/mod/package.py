"""Assemble the mod .pak: meta.lsx plus replacement .wem files at their original pak paths."""
from __future__ import annotations

import json
import uuid
import zipfile
from dataclasses import dataclass
from pathlib import Path

from bg3vm.game.lspk import write_pak
from bg3vm.mod.meta import build_meta_lsx, pack_version64, safe_folder


@dataclass
class BuiltMod:
    pak: Path
    zip: Path
    name: str
    folder: str
    uuid: str
    version64: int


def build_mod(out_dir: Path, name: str, wems: dict[str, bytes], mod_uuid: str | None = None) -> BuiltMod:
    """wems maps the original in-pak path (e.g. 'Localization/English/Voice/v123.wem') to new bytes."""
    folder = safe_folder(name)
    mod_uuid = mod_uuid or str(uuid.uuid4())
    meta = build_meta_lsx(name, folder, mod_uuid, description="Voice replacement generated by bg3vm")
    files = {f"Mods/{folder}/meta.lsx": meta.encode("utf-8"), **wems}
    out_dir.mkdir(parents=True, exist_ok=True)
    pak = out_dir / f"{folder}.pak"
    write_pak(pak, files)
    v64 = pack_version64(1, 0, 0, 0)
    info = {"Mods": [{"Author": "bg3vm", "Name": name, "Folder": folder, "Version": str(v64),
                      "Description": "", "UUID": mod_uuid, "Created": "", "Dependencies": [],
                      "Group": mod_uuid}], "MD5": ""}
    zp = out_dir / f"{folder}.zip"
    with zipfile.ZipFile(zp, "w") as z:
        z.write(pak, pak.name)
        z.writestr("info.json", json.dumps(info, indent=2))
    return BuiltMod(pak, zp, name, folder, mod_uuid, v64)
